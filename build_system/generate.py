#!/usr/bin/env python3
"""Turn the build_system YAML tree into the two files a build needs.

    python3 build_system/generate.py <part> [key=value ...]
    python3 build_system/generate.py atmega328p f_cpu=8000000 baudrate=38400

Reads tree_root.yaml, the part's trunk and branch, applies the leaf (the key=value
overrides) and writes, under <files.build>/<part>/:
  build.mk      Make variables: toolchain, flags, paths, flash and dist data
  mdt_target.h  the configuration macros the C code uses (F_CPU, baud rate, ...)
and prints that directory, relative to the repository root, for the Makefile.

A file is rewritten only when its content changes, so Make can run this on every
build without forcing a full recompile.
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
TREE = ROOT / "build_system"


class DescriptorError(Exception):
    """A part, leaf value or descriptor that cannot be built."""


def load_yaml(path: Path) -> dict:
    return yaml.safe_load(path.read_text())


def find_node(root: dict, part: str) -> tuple:
    """Return (platform, node name as written in the branch) for a part, case-insensitive."""
    for platform in root["platform"]:
        for branch_path in sorted((TREE / platform).glob("tree_branch_*.yaml")):
            for node in load_yaml(branch_path)["nodes"]:
                if node.lower() == part.lower():
                    return platform, node
    raise DescriptorError(f"unsupported part {part!r}: not a node in build_system/*/tree_branch_*.yaml")


def parse_leaf(pairs: list, defaults: dict) -> dict:
    """key=value strings -> values typed like the defaults they override."""
    leaf = {}
    for pair in pairs:
        key, sep, raw = pair.partition("=")
        if not sep or key not in defaults:
            raise DescriptorError(f"unknown setting {pair!r}; known: {', '.join(sorted(defaults))}")
        leaf[key] = _coerce(key, raw.strip(), type(defaults[key]))
    return leaf


def _coerce(key: str, raw: str, kind: type):
    if kind is bool:
        if raw.lower() in ("1", "true", "yes", "on"):
            return True
        if raw.lower() in ("0", "false", "no", "off"):
            return False
    elif kind is int:
        try:
            return int(raw.rstrip("uUlL"), 0)   # accepts 16000000UL as written in Makefiles
        except ValueError:
            pass
    elif raw:
        return raw
    raise DescriptorError(f"{key}={raw!r} is not a valid {kind.__name__}")


def validate(config: dict, trunk: dict) -> None:
    """Fail early with a clear message instead of a _Static_assert deep in the C build."""
    problems = []
    if config["f_cpu"] <= 0:
        problems.append("f_cpu must be > 0")
    if config["baudrate"] <= 0:
        problems.append("baudrate must be > 0")
    if config["buffer_size"] not in (32, 64, 128):
        problems.append("buffer_size must be 32, 64 or 128 (power of two, uint8_t index, holds one 18-byte packet)")
    for key in ("breakpoints", "watchpoints"):
        if not 1 <= config[key] <= 8:
            problems.append(f"{key} must be 1..8 (8-bit mask)")
    if config["uart_idle"] and not trunk["features"]["uart_idle"]:
        problems.append(f"uart_idle=true is not supported on {trunk['platform']}")
    if problems:
        raise DescriptorError("; ".join(problems))


def resolve(part: str, leaf_pairs: list = ()) -> dict:
    """Everything the two output files need, from the tree plus the leaf."""
    root = load_yaml(TREE / "tree_root.yaml")
    platform, node = find_node(root, part)
    trunk = load_yaml(TREE / platform / "tree_trunk.yaml")
    defaults = {**root["mdt_defaults"], **trunk["mdt_defaults"]}
    config = {**defaults, **parse_leaf(list(leaf_pairs), defaults)}
    validate(config, trunk)
    return {"root": root, "trunk": trunk, "platform": platform, "part": node.lower(), "config": config}


def render_build_mk(target: dict) -> str:
    root, trunk, config, part = target["root"], target["trunk"], target["config"], target["part"]
    build, flash, dist = trunk["build"], trunk["flash"], trunk["dist"]
    prefix = trunk["toolchain"]["prefix"]
    part_flag = build["part_flag"] + part
    elf = config["elf"]
    lines = [
        f"# Generated by build_system/generate.py for {part}. Do not edit: change the YAML instead.",
        f"TARGET_PLATFORM := {target['platform']}",
        f"TARGET_MCU := {part}",
        f"CC := {prefix}gcc",
        f"AR := {prefix}ar",
        f"OBJCOPY := {prefix}objcopy",
        f"SIZE := {prefix}size",
        f"SRC_DIR := {root['files']['src']}",
        f"INC_DIR := {root['files']['inc']}",
        f"HAL_DIR := {build['hal_dir']}",
        f"EXAMPLE_DIR := {build['example_dir']}",
        f"BUILD_DIR := {root['files']['build']}/{part}",
        f"LIB := {build['lib']}",
        f"ELF := {elf}",
        f"HEX := {Path(elf).stem}.hex",
        f"CFLAGS := {' '.join([part_flag, *build['flags']['compile']])}",
        f"LDFLAGS := {' '.join([part_flag, *build['flags']['link']])}",
        f"HEX_FLAGS := {' '.join(build['hex'])}",
        f"PORT := {config['port']}",
        f"TARGET_BAUDRATE := {config['baudrate']}",
        f"FLASH_TOOL := {flash['tool']}",
        f"FLASH_PROGRAMMER := {flash['programmer']}",
        f"FLASH_PROGRAMMER_BAUD := {flash['programmer_baud']}",
        f"DIST_HEADERS := {' '.join(dist['headers'])}",
        f"DIST_EXAMPLE_MAIN := {dist['example']['main']}",
        f"DIST_EXAMPLE_MAKEFILE := {dist['example']['makefile']}",
        f"DIST_EMPTY := {' '.join(dist['empty'])}",
    ]
    return "\n".join(lines) + "\n"


def render_target_header(target: dict) -> str:
    config, part = target["config"], target["part"]
    return f"""\
/* Generated by build_system/generate.py for {part}. Do not edit: change the YAML instead. */
#ifndef MDT_TARGET_H
#define MDT_TARGET_H

#define PLATFORM_{target['platform'].upper()} 1
#define MDT_TARGET_MCU "{part}"

#define F_CPU                   {config['f_cpu']}UL
#define MDT_FEATURE_UART_IDLE   {int(config['uart_idle'])}
#define MDT_UART_BAUDRATE       {config['baudrate']}
#define MDT_BUFFER_SIZE         {config['buffer_size']}
#define MDT_MAX_BREAKPOINTS     {config['breakpoints']}
#define MDT_MAX_WATCHPOINTS     {config['watchpoints']}

#endif /* MDT_TARGET_H */
"""


def write_if_changed(path: Path, text: str) -> bool:
    """Keep the timestamp when nothing changed, so Make does not rebuild everything."""
    if path.is_file() and path.read_text() == text:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)
    return True


def generate(part: str, leaf_pairs: list = (), out_dir: Path = None) -> Path:
    target = resolve(part, leaf_pairs)
    out_dir = out_dir or ROOT / target["root"]["files"]["build"] / target["part"]
    write_if_changed(out_dir / "build.mk", render_build_mk(target))
    write_if_changed(out_dir / "mdt_target.h", render_target_header(target))
    return out_dir


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("part", help="a node name, e.g. atmega328p (case-insensitive)")
    ap.add_argument("leaf", nargs="*", help="overrides, e.g. f_cpu=8000000 baudrate=38400")
    args = ap.parse_args()
    try:
        out_dir = generate(args.part, args.leaf)
    except DescriptorError as exc:
        print(f"generate.py: error: {exc}", file=sys.stderr)
        return 1
    print(out_dir.relative_to(ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
